// Regenerate src/domain/seriesData.ts from the research files in docs/.
//   node scripts/generate-series.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const files = ['docs/series-sources.json', 'docs/series-sources-2.json']
const conf = { high: 'alta', medium: 'media', low: 'bassa' }
const OPEN = '9999-12-31' // series still on sale

// Hand-written notes for the 30-year series (Italian, shown in the app).
const notes = {
  Q: 'Interessi capitalizzati al netto della ritenuta. Per gli anni 21-30 Poste applica il 12% semplice sul montante del 20° anno; sui moduli cartacei originali valgono gli importi stampati sul retro.',
  R: "Interessi capitalizzati al netto della ritenuta; anni 21-30 all'11,5% senza capitalizzazione.",
  S: 'Interessi capitalizzati al netto della ritenuta; anni 21-30 allo 0,5% semplice.',
  T: 'Capitalizzazione al netto della ritenuta secondo la tabella del decreto; un articolo è ambiguo per le persone fisiche.',
  U: 'Decreto istitutivo non trovato: tassi dalla tabella storica Poste, capitalizzazione al netto della ritenuta presunta come per la serie T.',
  V: 'Interessi capitalizzati al lordo; ritenuta del 12,5% applicata al rimborso.',
  W: 'Interessi capitalizzati al lordo; ritenuta del 12,5% applicata al rimborso.',
  X: 'Emessa in euro e, fino a esaurimento, in lire. Interessi capitalizzati al lordo; ritenuta al rimborso.',
  Y: 'Buono a 30 anni: interessi capitalizzati al lordo per 20 anni, poi 0,5% semplice fino al 31/12 del 30° anno.',
  Z: 'Buono a 30 anni: interessi capitalizzati al lordo per 20 anni, poi 0,5% semplice fino al 31/12 del 30° anno.',
}
const NET_TAX = new Set(['Q', 'R', 'S', 'T', 'U'])
const LOW = new Set(['U'])

const rules = []
for (const f of files) {
  for (const s of JSON.parse(readFileSync(f, 'utf8')).series) {
    const code = s.codes[0]
    const thirty = s.durationYears === 30
    const verified = s.formulaMatches === true || /formula reproduces it: True/.test(s.notes ?? '')
    rules.push({
      codes: s.codes,
      label: `Buono ordinario ${thirty ? 30 : 20} anni, serie ${code}`,
      currency: s.currency,
      issueFrom: s.issueFrom,
      issueTo: s.issueTo ?? OPEN,
      durationYears: s.durationYears,
      maturity: thirty ? 'endOfYear' : 'anniversary',
      compoundYears: 20,
      rateSchedule: s.rateSchedule.map((r) => ({ fromYear: r.fromYear, toYear: r.toYear, ratePct: r.grossRatePct })),
      taxMode: NET_TAX.has(code) ? 'net' : 'gross',
      taxPct: 12.5,
      prescriptionYears: 10,
      confidence: LOW.has(code) ? 'bassa' : conf[s.confidence],
      notes:
        notes[code] ??
        (verified
          ? 'Tassi annui dal foglio informativo della serie; la formula riproduce il coefficiente ufficiale di rimborso a 20 anni.'
          : 'Tassi annui da fonti ufficiali; coefficiente ufficiale a 20 anni non disponibile per la verifica.'),
      sources: s.sources,
    })
  }
}
rules.sort((a, b) => (a.issueFrom < b.issueFrom ? -1 : 1))

const out = [
  "import type { SeriesRule } from './series'",
  '',
  '// Generated by scripts/generate-series.mjs from docs/series-sources*.json.',
  '// Official CDP / Poste / Gazzetta Ufficiale sources; see docs/series.md.',
  'export const SERIES_RULES: SeriesRule[] = [',
  ...rules.map((r) => '  ' + JSON.stringify(r) + ','),
  ']',
  '',
]
writeFileSync('src/domain/seriesData.ts', out.join('\n'))
console.log(`${rules.length} series written`)
